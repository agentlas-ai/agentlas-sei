def resolve_locale(requested: str | None = None) -> str:
    value = (requested or "auto").strip()
    if value.lower() != "auto":
        return _normalize_locale(value)
    for env_name in ("SEI_LANG", "LC_ALL", "LC_MESSAGES", "LANG"):
        env_value = os.environ.get(env_name, "").strip()
        if env_value:
            return _normalize_locale(env_value)
    return "en"


def _normalize_locale(value: str) -> str:
    normalized = value.strip().lower().replace("_", "-").split(".", 1)[0]
    base = normalized.split("-", 1)[0]
    return _LOCALE_ALIASES.get(base, "en")


def translate(
    locale: str,
    key: str,
    values: Mapping[str, Any] | None = None,
) -> str:
    selected = resolve_locale(locale)
    template = TRANSLATIONS[selected].get(key, TRANSLATIONS["en"].get(key, key))
    return template.format_map(dict(values or {}))
